#!/usr/bin/env python3
"""Generate skills/blender-director/references/skill-catalog.md from every SKILL.md frontmatter.

The catalog is the director's explicit routing table: one row per skill with its category, pipeline
stage, job (the description's first sentence) and shipped scripts. Skill names are always visible to the
model even when the skill listing runs over budget and descriptions are dropped, so the director can map
any name to its job from here.

    python scripts/build_catalog.py           # write the catalog
    python scripts/build_catalog.py --check   # exit 1 if the catalog is stale (used by validate_skills.py)
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "skills" / "blender-director" / "references" / "skill-catalog.md"
ORDER = ["core", "production", "discipline", "delivery", "style", "mood", "world", "genre"]
TITLES = {"core": "Core (load first)", "production": "Production (film, AI handoff)",
          "discipline": "Disciplines", "delivery": "Delivery (optimize, collide, export)",
          "style": "Art styles (pick at most one unless the brief mixes them)", "mood": "Moods",
          "world": "Worlds and eras", "genre": "Game genres"}


def _field(fm, key):
    """Decoded frontmatter value (top level or under metadata), via the validator's own parser."""
    from validate_skills import parse_frontmatter
    data, _ = parse_frontmatter("---\n" + fm.strip("\n") + "\n---\n")
    value = data.get(key, (data.get("metadata") or {}).get(key, ""))
    return value if isinstance(value, str) else ""


def rows():
    out = []
    for p in sorted((ROOT / "skills").glob("*/SKILL.md")):
        text = p.read_text(encoding="utf-8")
        fm = text.split("---", 2)[1]
        desc = _field(fm, "description")
        job = re.split(r"(?<=[.!?])\s", desc, maxsplit=1)[0]
        scripts = sorted(s.name for s in (p.parent / "scripts").glob("*.py")) if (p.parent / "scripts").is_dir() else []
        out.append({"name": p.parent.name, "category": _field(fm, "category"), "stage": _field(fm, "stage"),
                    "job": job, "scripts": scripts})
    return out


def render(rs):
    lines = ["# Skill Catalog", "",
             "Generated by `scripts/build_catalog.py` from each skill's frontmatter; do not edit by hand.",
             "Route by job, not by keyword: pick the discipline skill for the work, add at most one style, mood,",
             "world and genre pack unless the brief says otherwise, and name the chosen skills in the brief.",
             "Stages: inspect, brief, model, look_dev, light_camera, animate, validate, export, any.", ""]
    for cat in ORDER + sorted({r["category"] for r in rs} - set(ORDER)):
        group = [r for r in rs if r["category"] == cat]
        if not group:
            continue
        lines += [f"## {TITLES.get(cat, cat)}", "", "| Skill | Stage | Job | Scripts |", "|---|---|---|---|"]
        for r in group:
            job = r["job"].replace("|", "/")
            lines.append(f"| `{r['name']}` | {r['stage']} | {job} | {', '.join(r['scripts']) or '-'} |")
        lines.append("")
    return "\n".join(lines)


def main(argv):
    text = render(rows())
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"stale: {OUT.relative_to(ROOT)} (run python scripts/build_catalog.py)")
            return 1
        print("catalog up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(rows())} skills)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
